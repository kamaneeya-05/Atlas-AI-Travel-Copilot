import { clsx } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs) {
  return twMerge(clsx(inputs));
}

export function formatDate(dateString) {
  if (!dateString) return '';
  return new Date(dateString).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

export function formatRelativeTime(dateString) {
  if (!dateString) return '';
  const date = new Date(dateString);
  const now = new Date();
  const diffMs = now - date;
  const diffMins = Math.floor(diffMs / 60000);
  const diffHours = Math.floor(diffMs / 3600000);
  const diffDays = Math.floor(diffMs / 86400000);

  if (diffMins < 1) return 'Just now';
  if (diffMins < 60) return `${diffMins}m ago`;
  if (diffHours < 24) return `${diffHours}h ago`;
  if (diffDays < 7) return `${diffDays}d ago`;
  return formatDate(dateString);
}

export function truncate(str, length = 80) {
  if (!str) return '';
  return str.length > length ? str.slice(0, length) + '…' : str;
}

export function capitalize(str) {
  if (!str) return '';
  return str.charAt(0).toUpperCase() + str.slice(1);
}

export function slugify(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export function getDestinationImage(destination) {
  // Use picsum for deterministic placeholder images
  return `https://picsum.photos/seed/${slugify(destination || 'travel')}/800/400`;
}

export function tripItineraryToText(trip) {
  if (!trip) return '';
  const lines = [];
  lines.push(`✈ ${trip.title || trip.destination}`);
  lines.push(`📍 ${trip.destination} · ${trip.duration}`);
  if (trip.summary) lines.push(`\n${trip.summary}`);

  const timeline = trip.blocks?.find((b) => b.type === 'timeline');
  if (timeline?.days) {
    lines.push('\n--- ITINERARY ---');
    timeline.days.forEach((day) => {
      lines.push(`\nDay ${day.day}: ${day.title}`);
      day.activities?.forEach((a) => {
        lines.push(`  ${a.time} - ${a.name}: ${a.description}`);
      });
    });
  }

  const budget = trip.blocks?.find((b) => b.type === 'budget');
  if (budget) {
    lines.push(`\n--- BUDGET ---`);
    lines.push(`Total: ${budget.totalEstimate} (${budget.currency})`);
  }

  lines.push(`\n— Generated by ATLAS AI`);
  return lines.join('\n');
}
