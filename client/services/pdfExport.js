/**
 * ATLAS AI – PDF Export
 * Uses jsPDF with proper font handling for ₹ symbol and clean layout
 */
export async function exportToPDF(trip) {
  const { jsPDF } = await import('jspdf');

  const doc = new jsPDF({ orientation: 'p', unit: 'mm', format: 'a4' });

  const PW      = doc.internal.pageSize.getWidth();
  const PH      = doc.internal.pageSize.getHeight();
  const ML      = 18;   // margin left
  const MR      = 18;   // margin right
  const CW      = PW - ML - MR; // content width
  const MB      = 20;   // margin bottom
  let   y       = 0;

  // ── Colour palette ──────────────────────────────────────────────────────
  const PURPLE  = [99,  102, 241];
  const DARK    = [30,  30,  40];
  const GREY    = [100, 100, 110];
  const LGREY   = [220, 220, 228];
  const WHITE   = [255, 255, 255];
  const RED     = [180, 40,  40];
  const GREEN   = [22,  163, 74];
  const AMBER   = [180, 120, 0];

  // Replace ₹ with Rs. and strip ALL emoji/special unicode that jsPDF can't render
  const safe = (str) => {
    if (!str) return '';
    return String(str)
      .replace(/₹/g, 'Rs.')
      .replace(/\u20b9/g, 'Rs.')
      .replace(/\u2605|\u2606/g, '*')        // ★ ☆ → *
      .replace(/[\u{1F000}-\u{1FFFF}]/gu, '') // emoji block 1
      .replace(/[\u{2700}-\u{27BF}]/gu, '')   // dingbats
      .replace(/[\u{1F300}-\u{1F9FF}]/gu, '') // misc emoji
      .replace(/[^\x20-\x7F\u00C0-\u024F\u2019\u2018\u201C\u201D]/g, '')
      .replace(/[\u2018\u2019]/g, "'")         // smart quotes
      .replace(/[\u201C\u201D]/g, '"')
      .trim();
  };

  // ── Helpers ─────────────────────────────────────────────────────────────
  function newPage() {
    addFooter();
    doc.addPage();
    y = ML;
  }

  function checkY(needed) {
    if (y + needed > PH - MB) newPage();
  }

  function setFont(style = 'normal', size = 10, color = DARK) {
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
  }

  function text(str, x, yPos, opts = {}) {
    doc.text(safe(str), x, yPos, opts);
  }

  function wrappedText(str, x, yPos, maxW, lineH = 5) {
    const lines = doc.splitTextToSize(safe(str), maxW);
    lines.forEach((line, i) => {
      checkY(lineH + 2);
      doc.text(line, x, yPos + i * lineH);
    });
    return lines.length * lineH;
  }

  function sectionHeader(title, color = PURPLE) {
    checkY(14);
    // Colored left bar
    doc.setFillColor(...color);
    doc.rect(ML, y, 3, 7, 'F');
    setFont('bold', 12, color);
    text(title, ML + 6, y + 5.5);
    y += 10;
    // Divider line
    doc.setDrawColor(...LGREY);
    doc.setLineWidth(0.3);
    doc.line(ML, y, PW - MR, y);
    y += 4;
  }

  function pill(label, x, yPos, bgColor, textColor = WHITE) {
    const w  = doc.getTextWidth(safe(label)) + 6;
    const h  = 5;
    doc.setFillColor(...bgColor);
    doc.roundedRect(x, yPos - 3.5, w, h, 1.5, 1.5, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(...textColor);
    text(label, x + 3, yPos);
    return w + 3;
  }

  function addFooter() {
    const pg    = doc.internal.getCurrentPageInfo().pageNumber;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...GREY);
    doc.setDrawColor(...LGREY);
    doc.setLineWidth(0.2);
    doc.line(ML, PH - 12, PW - MR, PH - 12);
    text(`Generated by ATLAS AI`, ML, PH - 7);
    text(`Page ${pg}`, PW / 2, PH - 7, { align: 'center' });
    text(new Date().toLocaleDateString('en-IN'), PW - MR, PH - 7, { align: 'right' });
  }

  // ════════════════════════════════════════════════════════════════════════
  // COVER HEADER
  // ════════════════════════════════════════════════════════════════════════
  y = 0;

  // Purple header band
  doc.setFillColor(...PURPLE);
  doc.rect(0, 0, PW, 38, 'F');

  // Logo circle
  doc.setFillColor(255, 255, 255, 0.2);
  doc.circle(ML + 5, 14, 5, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(...WHITE);
  text('A', ML + 3, 16.5);

  // Title
  setFont('bold', 22, WHITE);
  text(trip.title || trip.destination, ML + 14, 16);

  // Subtitle row
  setFont('normal', 9, [220, 220, 255]);
  const subtitle = [
    trip.destination,
    trip.duration,
    'Generated by ATLAS AI',
  ].filter(Boolean).join('  ·  ');
  text(subtitle, ML + 14, 24);

  y = 46;

  // Summary
  if (trip.summary) {
    checkY(16);
    setFont('normal', 9.5, GREY);
    const h = wrappedText(trip.summary, ML, y, CW, 5.5);
    y += h + 8;
  }

  // ── Trip Info chips ──────────────────────────────────────────────────
  checkY(12);
  const infoItems = [
    trip.bestTimeToVisit && `Best time: ${trip.bestTimeToVisit}`,
    trip.language        && `Language: ${trip.language}`,
    trip.currency        && safe(trip.currency),
    trip.timezone        && trip.timezone,
  ].filter(Boolean);

  let cx = ML;
  infoItems.forEach((info) => {
    if (cx + doc.getTextWidth(safe(info)) + 10 > PW - MR) { cx = ML; y += 7; }
    const w = pill(info, cx, y + 3, [230, 232, 255], [60, 60, 180]);
    cx += w + 2;
  });
  y += 10;

  // ════════════════════════════════════════════════════════════════════════
  // BLOCKS
  // ════════════════════════════════════════════════════════════════════════

  for (const block of (trip.blocks || [])) {
    if (!block?.type) continue;

    // ── OVERVIEW ────────────────────────────────────────────────────────
    if (block.type === 'overview') {
      sectionHeader('DESTINATION OVERVIEW');

      const cols = [
        { label: 'Highlights',   items: block.highlights  || [] },
        { label: 'Must See',     items: block.mustSee     || [] },
        { label: 'Local Tips',   items: block.localTips   || [] },
      ].filter(c => c.items.length > 0);

      cols.forEach((col) => {
        checkY(10);
        setFont('bold', 9, PURPLE);
        text(col.label, ML, y);
        y += 5;
        col.items.forEach((item) => {
          checkY(6);
          doc.setFillColor(...PURPLE);
          doc.circle(ML + 1.5, y - 1, 1, 'F');
          setFont('normal', 9, DARK);
          const h = wrappedText(item, ML + 5, y, CW - 5, 4.8);
          y += Math.max(h, 5);
        });
        y += 3;
      });

      if (block.transportation) {
        checkY(14);
        setFont('bold', 9, PURPLE);
        text('Getting Around', ML, y);
        y += 5;
        setFont('normal', 9, DARK);
        const h = wrappedText(block.transportation, ML, y, CW, 4.8);
        y += h + 6;
      }
    }

    // ── TIMELINE ────────────────────────────────────────────────────────
    else if (block.type === 'timeline') {
      sectionHeader('DAY-BY-DAY ITINERARY');

      for (const day of (block.days || [])) {
        checkY(18);

        // Day header
        doc.setFillColor(...PURPLE);
        doc.roundedRect(ML, y, CW, 9, 2, 2, 'F');
        setFont('bold', 10, WHITE);
        text(`Day ${day.day}`, ML + 3, y + 6);
        setFont('normal', 9, [220, 220, 255]);
        text(day.title || '', ML + 22, y + 6);
        y += 12;

        if (day.description) {
          setFont('italic', 8.5, GREY);
          const h = wrappedText(day.description, ML, y, CW, 4.5);
          y += h + 3;
        }

        for (const act of (day.activities || [])) {
          // Calculate dynamic card height
          const descLines = act.description
            ? doc.splitTextToSize(safe(act.description), CW - 40).length
            : 0;
          const actH = 12 + (descLines * 4) + (act.location ? 5 : 0) + 2;
          checkY(actH + 2);

          // Activity card background
          doc.setFillColor(245, 245, 252);
          doc.roundedRect(ML, y - 1, CW, actH, 1.5, 1.5, 'F');

          // Time badge
          doc.setFillColor(...PURPLE);
          doc.roundedRect(ML + 2, y + 0.5, 16, 7, 1.5, 1.5, 'F');
          setFont('bold', 7.5, WHITE);
          text(act.time || '', ML + 4, y + 5.5);

          // Activity name
          setFont('bold', 9, DARK);
          text(act.name || '', ML + 22, y + 5);

          // Cost (right aligned)
          if (act.cost) {
            setFont('bold', 8, GREEN);
            text(safe(act.cost), PW - MR, y + 5, { align: 'right' });
          }

          let cy = y + 10;

          // Description
          if (act.description) {
            setFont('normal', 8, GREY);
            const lines = doc.splitTextToSize(safe(act.description), CW - 40);
            lines.forEach(line => {
              doc.text(line, ML + 22, cy);
              cy += 4;
            });
          }

          // Location
          if (act.location) {
            setFont('italic', 7.5, GREY);
            text(`${act.location}`, ML + 22, cy);
            cy += 4;
          }

          y += actH + 3;
        }
        y += 4;
      }
    }

    // ── BUDGET ──────────────────────────────────────────────────────────
    else if (block.type === 'budget') {
      sectionHeader('BUDGET BREAKDOWN', [180, 120, 0]);
      checkY(12);

      // Total estimate box
      doc.setFillColor(255, 248, 230);
      doc.roundedRect(ML, y, CW, 12, 2, 2, 'F');
      setFont('bold', 13, [140, 90, 0]);
      text('Total Estimate:', ML + 4, y + 8);
      setFont('bold', 14, [140, 90, 0]);
      text(safe(block.totalEstimate || ''), ML + 52, y + 8);
      if (block.budgetLevel) {
        setFont('normal', 8, GREY);
        text(`(${block.budgetLevel})`, PW - MR - 2, y + 8, { align: 'right' });
      }
      y += 16;

      // Breakdown rows
      const barColors = {
        'Accommodation':  [99, 102, 241],
        'Food':           [22, 163, 74],
        'Transport':      [234, 179, 8],
        'Activities':     [217, 70, 239],
        'Shopping':       [249, 115, 22],
      };

      for (const item of (block.breakdown || [])) {
        checkY(10);
        const pct      = Math.min(Number(item.percentage) || 0, 100);
        const barColor = Object.entries(barColors).find(([k]) =>
          item.category?.toLowerCase().includes(k.toLowerCase())
        )?.[1] || PURPLE;

        // Category label
        setFont('normal', 9, DARK);
        text(item.category || '', ML, y + 4);

        // Amount (right)
        setFont('bold', 9, DARK);
        text(safe(item.amount || ''), PW - MR, y + 4, { align: 'right' });

        // Progress bar background
        const barX = ML + 45;
        const barW = CW - 70;
        const barH = 3;
        doc.setFillColor(...LGREY);
        doc.roundedRect(barX, y + 1, barW, barH, 1, 1, 'F');

        // Progress bar fill
        if (pct > 0) {
          doc.setFillColor(...barColor);
          doc.roundedRect(barX, y + 1, barW * pct / 100, barH, 1, 1, 'F');
        }

        // Percentage
        setFont('normal', 7.5, GREY);
        text(`${pct}%`, barX + barW + 2, y + 4);

        // Notes
        if (item.notes) {
          setFont('italic', 7.5, GREY);
          text(item.notes, ML + 1, y + 8);
        }

        y += 11;
      }

      // Saving tips
      if ((block.savingTips || []).length > 0) {
        y += 3;
        checkY(10);
        doc.setFillColor(230, 255, 240);
        doc.roundedRect(ML, y, CW, 7 + block.savingTips.length * 5.5, 2, 2, 'F');
        y += 4;
        setFont('bold', 8.5, GREEN);
        text('Money-saving tips', ML + 3, y);
        y += 5;
        block.savingTips.forEach((tip) => {
          checkY(6);
          setFont('normal', 8, [30, 100, 50]);
          doc.circle(ML + 5, y - 1, 1, 'F');
          const h = wrappedText(tip, ML + 8, y, CW - 10, 4.5);
          y += Math.max(h, 5);
        });
        y += 4;
      }
    }

    // ── RESTAURANTS ─────────────────────────────────────────────────────
    else if (block.type === 'restaurants') {
      sectionHeader('RESTAURANT RECOMMENDATIONS', [217, 119, 6]);

      for (const r of (block.items || [])) {
        // Calculate dynamic height based on content
        const descLines = r.description
          ? doc.splitTextToSize(safe(r.description), CW - 8).length
          : 0;
        const cardH = 8 + 6 + (r.mustTry ? 6 : 0) + (descLines * 4.5) + (r.location || r.openHours ? 6 : 0) + 4;

        checkY(cardH + 4);

        doc.setFillColor(255, 250, 240);
        doc.roundedRect(ML, y, CW, cardH, 2, 2, 'F');

        let cy = y + 6;

        // Name
        setFont('bold', 10, DARK);
        text(r.name || '', ML + 4, cy);

        // Price range (right)
        if (r.priceRange) {
          setFont('bold', 8, [140, 100, 0]);
          text(safe(r.priceRange), PW - MR - 2, cy, { align: 'right' });
        }
        cy += 5.5;

        // Cuisine + rating
        setFont('normal', 8, GREY);
        const subLine = [r.cuisine, r.rating && `Rating: ${r.rating}/5`].filter(Boolean).join('  |  ');
        text(subLine, ML + 4, cy);
        cy += 5.5;

        // Must try
        if (r.mustTry) {
          setFont('italic', 8, [180, 80, 0]);
          text(`Must try: ${r.mustTry}`, ML + 4, cy);
          cy += 5.5;
        }

        // Description
        if (r.description) {
          setFont('normal', 8, GREY);
          const lines = doc.splitTextToSize(safe(r.description), CW - 8);
          lines.forEach(line => {
            doc.text(line, ML + 4, cy);
            cy += 4.5;
          });
        }

        // Location + hours
        const locFooter = [r.location, r.openHours].filter(Boolean).join('  |  ');
        if (locFooter) {
          setFont('italic', 7.5, GREY);
          text(locFooter, ML + 4, cy);
          cy += 5;
        }

        y += cardH + 4;
      }
    }

    // ── CHECKLIST ───────────────────────────────────────────────────────
    else if (block.type === 'checklist') {
      sectionHeader('PACKING CHECKLIST', [124, 58, 237]);

      for (const cat of (block.categories || [])) {
        checkY(12);
        setFont('bold', 9, [124, 58, 237]);
        text(cat.name || '', ML, y);
        y += 5;

        for (const item of (cat.items || [])) {
          checkY(6);
          // Checkbox
          doc.setDrawColor(150, 150, 160);
          doc.setLineWidth(0.4);
          doc.roundedRect(ML, y - 3, 4, 4, 0.5, 0.5);
          setFont(item.essential ? 'bold' : 'normal', 8.5, DARK);
          text(item.label || '', ML + 6, y);
          if (item.essential) {
            pill('Essential', PW - MR - 22, y - 3, [239, 68, 68]);
          }
          y += 5.5;
        }
        y += 3;
      }
    }

    // ── WEATHER ─────────────────────────────────────────────────────────
    else if (block.type === 'weather') {
      sectionHeader('WEATHER & CLIMATE', [14, 165, 233]);
      checkY(20);

      const weatherItems = [
        { label: 'Season',     value: block.season },
        { label: 'Avg Temp',   value: block.averageTemp },
        { label: 'Conditions', value: block.conditions },
      ].filter(i => i.value);

      const colW = CW / 3;
      weatherItems.forEach((item, idx) => {
        const x = ML + idx * colW;
        doc.setFillColor(230, 247, 255);
        doc.roundedRect(x, y, colW - 3, 16, 2, 2, 'F');
        setFont('bold', 7.5, [14, 100, 160]);
        text(item.label, x + 3, y + 5);
        setFont('normal', 9, DARK);
        wrappedText(item.value, x + 3, y + 10, colW - 7, 4);
      });
      y += 20;

      if ((block.whatToWear || []).length > 0) {
        checkY(10);
        setFont('bold', 8.5, [14, 100, 160]);
        text('What to wear:', ML, y);
        y += 5;
        setFont('normal', 8.5, DARK);
        text(block.whatToWear.join('  ·  '), ML, y);
        y += 7;
      }
    }

    // ── TIPS ────────────────────────────────────────────────────────────
    else if (block.type === 'tips') {
      sectionHeader('TRAVEL TIPS', [16, 185, 129]);

      const tipSections = [
        { label: 'Cultural',  items: block.cultural  || [], color: [0, 128, 90] },
        { label: 'Practical', items: block.practical || [], color: [0, 100, 160] },
        { label: 'Safety',    items: block.safety    || [], color: [180, 50, 50] },
      ].filter(s => s.items.length > 0);

      tipSections.forEach((section) => {
        checkY(10);
        setFont('bold', 9, section.color);
        text(section.label, ML, y);
        y += 5;
        section.items.forEach((tip) => {
          checkY(6);
          doc.setFillColor(...section.color);
          doc.circle(ML + 1.5, y - 1, 1, 'F');
          setFont('normal', 8.5, DARK);
          const h = wrappedText(tip, ML + 5, y, CW - 5, 4.5);
          y += Math.max(h, 5);
        });
        y += 3;
      });

      if ((block.apps || []).length > 0) {
        checkY(10);
        setFont('bold', 9, [80, 40, 160]);
        text('Recommended Apps:', ML, y);
        y += 5;
        let ax = ML;
        block.apps.forEach((app) => {
          if (ax + doc.getTextWidth(safe(app)) + 12 > PW - MR) {
            ax = ML; y += 7;
          }
          const w = pill(app, ax, y + 3, [124, 58, 237]);
          ax += w + 2;
        });
        y += 10;
      }
    }

    // ── WARNINGS ────────────────────────────────────────────────────────
    else if (block.type === 'warnings' && (block.items || []).length > 0) {
      sectionHeader('TRAVEL WARNINGS', RED);

      const severityColor = { high: RED, medium: AMBER, low: [0, 120, 180] };

      for (const w of block.items) {
        checkY(16);
        const col = severityColor[w.severity] || GREY;
        doc.setFillColor(...col, 0.1);
        doc.setFillColor(col[0] + 160, col[1] + 160, col[2] + 160);
        doc.roundedRect(ML, y, CW, 14, 2, 2, 'F');

        // Severity badge
        pill(
          (w.severity || 'low').toUpperCase(),
          ML + 3, y + 5,
          col
        );

        // Category + title
        setFont('bold', 9, DARK);
        text(w.title || '', ML + 30, y + 5);

        setFont('italic', 7.5, GREY);
        text(w.category || '', ML + 3, y + 10);

        // Description
        if (w.description) {
          setFont('normal', 8, DARK);
          const h = wrappedText(w.description, ML + 30, y + 10, CW - 35, 4.5);
          y += Math.max(h - 4.5, 0);
        }

        y += 17;
      }
    }
  }

  // Final footer
  addFooter();

  // Save
  const fname = `atlas-ai-${(trip.destination || 'trip').toLowerCase().replace(/[\s,]+/g, '-')}-${Date.now()}.pdf`;
  doc.save(fname);
}
